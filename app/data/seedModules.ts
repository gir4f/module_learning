import type { LearningModule } from '../types/learning'
import { makeSlug } from '../utils/slug'

const asset = (fileName: string) => `/module-assets/${encodeURIComponent(fileName)}`
const componentRows = (
  category: string,
  items: Array<[name: string, quantity: string, unit: string, note?: string | null]>,
) => items.map(([name, quantity, unit, note], sortOrder) => ({
  category,
  name,
  quantity,
  unit,
  note: note || null,
  sortOrder,
}))

function detail(title: string, options: Partial<LearningModule['details'][number]> = {}) {
  return {
    slug: options.slug || makeSlug(title),
    title,
    summary: options.summary || null,
    keywords: options.keywords || null,
    sortOrder: options.sortOrder || 0,
    components: options.components || [],
    attachments: options.attachments || [],
  }
}

